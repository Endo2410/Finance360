-- ===========================================
-- CREAR EJECUCION REBATE
-- ===========================================
CREATE OR ALTER PROCEDURE SP_CREAR_EJECUCION_REBATE
(
    @ID_ACUERDO INT,
    @MONTO_CALCULADO DECIMAL(18,2),
    @ARCHIVO_SOPORTE VARCHAR(300),
    @USUARIO_REGISTRO VARCHAR(100),   
    @IDESTADO INT = 1
)
AS
BEGIN
    SET NOCOUNT ON;

    DECLARE 
        @VALOR_CRITERIO DECIMAL(18,2),
        @GANANCIA DECIMAL(18,2),
        @OPERADOR VARCHAR(10),
        @CUMPLE_CONDICION BIT = 0,
        @MONTO_REBATE DECIMAL(18,2) = 0,
        @IDESTADO_FINAL INT;

    -- OBTENER DATOS DEL ACUERDO Y CRITERIO
    SELECT
        @VALOR_CRITERIO = A.VALOR_CRITERIO,
        @GANANCIA = A.GANANCIA,
        @OPERADOR = C.OPERADOR
    FROM ACUERDO_REBATE A
    INNER JOIN CRITERIO_REBATE C ON C.ID_CRITERIO = A.ID_CRITERIO
    WHERE A.ID_ACUERDO = @ID_ACUERDO;

    IF @OPERADOR IS NULL
    BEGIN
        RAISERROR('No se encontró el acuerdo o el criterio.',16,1);
        RETURN;
    END

    -- CALCULO DEL REBATE
    IF @OPERADOR = '>'
    BEGIN
        IF @MONTO_CALCULADO > @VALOR_CRITERIO
        BEGIN
            SET @CUMPLE_CONDICION = 1;
            SET @MONTO_REBATE = @GANANCIA * FLOOR(@MONTO_CALCULADO / @VALOR_CRITERIO);
        END
    END
    ELSE IF @OPERADOR = '>='
    BEGIN
        IF @MONTO_CALCULADO >= @VALOR_CRITERIO
        BEGIN
            SET @CUMPLE_CONDICION = 1;
            SET @MONTO_REBATE = @GANANCIA * FLOOR(@MONTO_CALCULADO / @VALOR_CRITERIO);
        END
    END
    ELSE IF @OPERADOR = '%'
    BEGIN
        IF @MONTO_CALCULADO >= @VALOR_CRITERIO
        BEGIN
            SET @CUMPLE_CONDICION = 1;
            SET @MONTO_REBATE = @MONTO_CALCULADO * (@GANANCIA / 100.0);
        END
    END
    ELSE
    BEGIN
        RAISERROR('Operador de criterio no soportado.',16,1);
        RETURN;
    END

    -- DETERMINAR ESTADO FINAL
    SET @IDESTADO_FINAL = CASE 
                              WHEN @CUMPLE_CONDICION = 0 THEN 4
                              WHEN EXISTS (SELECT 1 FROM ESTADO WHERE IDESTADO = @IDESTADO) THEN @IDESTADO
                              ELSE 1  -- Por defecto ACTIVO
                           END;

    -- INSERTAR EJECUCION
    INSERT INTO EJECUCION_REBATE
    (
        ID_ACUERDO,
        NUMERO_DOCUMENTO_SOPORTE,
        MONTO_CALCULADO,
        CUMPLE_CONDICION,
        MONTO_REBATE,
        ARCHIVO_SOPORTE,
        IDESTADO,
		USUARIO_REGISTRO    
    )
    VALUES
    (
        @ID_ACUERDO,
        'REB-' + FORMAT(NEXT VALUE FOR SEQ_NUMERO_EJECUCION_REBATE,'000000'),
        @MONTO_CALCULADO,
        @CUMPLE_CONDICION,
        @MONTO_REBATE,
        @ARCHIVO_SOPORTE,
        @IDESTADO_FINAL,
		 @USUARIO_REGISTRO  
    );
END
GO

-- ===========================================
-- EDITAR EJECUCION REBATE
-- ===========================================
CREATE OR ALTER PROCEDURE SP_EDITAR_EJECUCION_REBATE
(
    @ID_EJECUCION INT,
    @MONTO_CALCULADO DECIMAL(18,2) = NULL,
    @ARCHIVO_SOPORTE VARCHAR(300) = NULL
)
AS
BEGIN
    SET NOCOUNT ON;

    DECLARE
        @ID_ACUERDO INT,
        @VALOR_CRITERIO DECIMAL(18,2),
        @GANANCIA DECIMAL(18,2),
        @OPERADOR VARCHAR(10),
        @MONTO_ANT DECIMAL(18,2),
        @ARCHIVO_ANT VARCHAR(300),
        @CUMPLE_CONDICION BIT = 0,
        @MONTO_REBATE DECIMAL(18,2) = 0,
        @IDESTADO_FINAL INT,
        @MONTO_CALC DECIMAL(18,2);

    -- DATOS DE LA EJECUCIÓN
    SELECT 
        @ID_ACUERDO = ID_ACUERDO,
        @MONTO_ANT = MONTO_CALCULADO,
        @ARCHIVO_ANT = ARCHIVO_SOPORTE
    FROM EJECUCION_REBATE
    WHERE ID_EJECUCION = @ID_EJECUCION;

    IF @ID_ACUERDO IS NULL
    BEGIN
        RAISERROR('No se encontró la ejecución.',16,1);
        RETURN;
    END

    -- DATOS DEL ACUERDO Y CRITERIO
    SELECT
        @VALOR_CRITERIO = A.VALOR_CRITERIO,
        @GANANCIA = A.GANANCIA,
        @OPERADOR = C.OPERADOR
    FROM ACUERDO_REBATE A
    INNER JOIN CRITERIO_REBATE C ON C.ID_CRITERIO = A.ID_CRITERIO
    WHERE A.ID_ACUERDO = @ID_ACUERDO;

    IF @OPERADOR IS NULL
    BEGIN
        RAISERROR('No se encontró el criterio del acuerdo.',16,1);
        RETURN;
    END

    -- MONTO A EVALUAR
    SET @MONTO_CALC = ISNULL(@MONTO_CALCULADO, @MONTO_ANT);

    -- CALCULO DEL REBATE (MISMA LÓGICA QUE CREAR)
    IF @OPERADOR = '>'
    BEGIN
        IF @MONTO_CALC > @VALOR_CRITERIO
        BEGIN
            SET @CUMPLE_CONDICION = 1;
            SET @MONTO_REBATE = @GANANCIA * FLOOR(@MONTO_CALC / @VALOR_CRITERIO);
        END
    END
    ELSE IF @OPERADOR = '>='
    BEGIN
        IF @MONTO_CALC >= @VALOR_CRITERIO
        BEGIN
            SET @CUMPLE_CONDICION = 1;
            SET @MONTO_REBATE = @GANANCIA * FLOOR(@MONTO_CALC / @VALOR_CRITERIO);
        END
    END
    ELSE IF @OPERADOR = '%'
    BEGIN
        IF @MONTO_CALC >= @VALOR_CRITERIO
        BEGIN
            SET @CUMPLE_CONDICION = 1;
            SET @MONTO_REBATE = @MONTO_CALC * (@GANANCIA / 100.0);
        END
    END

    -- 🔥 ESTADO FINAL (IGUAL QUE CREAR)
    SET @IDESTADO_FINAL = CASE 
                              WHEN @CUMPLE_CONDICION = 0 THEN 4
                              ELSE 1
                          END;

    -- ACTUALIZAR EJECUCIÓN
    UPDATE EJECUCION_REBATE
    SET
        MONTO_CALCULADO = @MONTO_CALC,
        CUMPLE_CONDICION = @CUMPLE_CONDICION,
        MONTO_REBATE = @MONTO_REBATE,
        ARCHIVO_SOPORTE = ISNULL(@ARCHIVO_SOPORTE, @ARCHIVO_ANT),
        IDESTADO = @IDESTADO_FINAL
    WHERE ID_EJECUCION = @ID_EJECUCION;
END
GO



