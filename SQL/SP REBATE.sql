CREATE OR ALTER PROCEDURE SP_REGISTRAR_PAGO_REBATE
(
    @ID_ACUERDO INT,
    @FECHA_DOCUMENTO DATE,
    @MONTO_TOTAL DECIMAL(18,2),
    @OBSERVACION VARCHAR(300),
    @DETALLE T_DETALLE_PAGO_REBATE READONLY,
    @ID_PAGO_REBATE INT OUTPUT,
    @NUMERO_DOCUMENTO_OUT VARCHAR(20) OUTPUT
)
AS
BEGIN
    SET NOCOUNT ON;

    DECLARE @CORRELATIVO INT;
    DECLARE @LARGO INT;

    BEGIN TRY
        BEGIN TRAN;

        /* ===============================
           GENERAR NÚMERO DE DOCUMENTO
           =============================== */
        SELECT @CORRELATIVO = ISNULL(MAX(CAST(NUMERO_DOCUMENTO AS INT)), 0) + 1
        FROM PAGO_REBATE;

        SET @LARGO = CASE 
                        WHEN LEN(@CORRELATIVO) < 4 THEN 4 
                        ELSE LEN(@CORRELATIVO) 
                     END;

        SET @NUMERO_DOCUMENTO_OUT =
            RIGHT(REPLICATE('0', @LARGO) + CAST(@CORRELATIVO AS VARCHAR), @LARGO);

        /* ===============================
           INSERT CABECERA DE PAGO
           =============================== */
        INSERT INTO PAGO_REBATE
        (
            ID_ACUERDO,
            NUMERO_DOCUMENTO,
            MONTO_TOTAL,
            OBSERVACION,
            IDESTADO,
            FECHA_REGISTRO
        )
        VALUES
        (
            @ID_ACUERDO,
            @NUMERO_DOCUMENTO_OUT,
            @MONTO_TOTAL,
            @OBSERVACION,
            6,             -- PAGADO
            GETDATE()
        );

        SET @ID_PAGO_REBATE = SCOPE_IDENTITY();

        /* ===============================
           INSERT DETALLE DE PAGO
           =============================== */
        INSERT INTO DETALLE_PAGO_REBATE
        (
            ID_PAGO_REBATE,
            ID_EJECUCION,
            MONTO_PAGADO,
            ID_TIPO_DOC,
            COMPROBANTE,
            USUARIO_PAGO
        )
        SELECT
            @ID_PAGO_REBATE,
            ID_EJECUCION,
            MONTO_PAGADO,
            ID_TIPO_DOCUMENTO,
            COMPROBANTE,
            USUARIO_PAGO
        FROM @DETALLE;

        /* ===============================
           ACTUALIZAR EJECUCIONES A PAGADAS
           =============================== */
        UPDATE ER
        SET ER.IDESTADO = 6   -- PAGADO
        FROM EJECUCION_REBATE ER
        INNER JOIN @DETALLE D 
            ON ER.ID_EJECUCION = D.ID_EJECUCION;

        COMMIT;
    END TRY
    BEGIN CATCH
        ROLLBACK;
        THROW;
    END CATCH
END;
GO


CREATE OR ALTER PROCEDURE SP_LISTA_EJECUCIONES_REBATE_RESUMEN
AS
BEGIN
    SET NOCOUNT ON;

    SELECT
        ER.ID_EJECUCION,
        ER.NUMERO_DOCUMENTO_SOPORTE,

        A.NUMERO_ACUERDO,
        A.NOMBRE_ACUERDO,

        P.NOMBRE_PROVEEDOR,
        TR.NOMBRE AS TIPO_REBATE,
        CR.NOMBRE AS CRITERIO,

        ER.MONTO_REBATE,

        ISNULL(SUM(DPR.MONTO_PAGADO), 0) AS MONTO_PAGADO,
        ER.MONTO_REBATE - ISNULL(SUM(DPR.MONTO_PAGADO), 0) AS SALDO_PENDIENTE,

        ER.IDESTADO AS ID_ESTADO_EJECUCION,
        E.NOMBRE AS ESTADO_EJECUCION,

        ER.FECHA_REGISTRO
    FROM EJECUCION_REBATE ER
        INNER JOIN ACUERDO_REBATE A ON A.ID_ACUERDO = ER.ID_ACUERDO
        INNER JOIN PROVEEDORES P ON P.ID_PROVEEDOR = A.ID_PROVEEDOR
        INNER JOIN TIPO_REBATE TR ON TR.ID_TIPO_REBATE = A.ID_TIPO_REBATE
        INNER JOIN CRITERIO_REBATE CR ON CR.ID_CRITERIO = A.ID_CRITERIO
        INNER JOIN ESTADO E ON E.IDESTADO = ER.IDESTADO
        LEFT JOIN DETALLE_PAGO_REBATE DPR ON DPR.ID_EJECUCION = ER.ID_EJECUCION
    WHERE
        ER.IDESTADO IN (1, 6)      -- 👈 SOLO PENDIENTE Y PAGADO
    GROUP BY
        ER.ID_EJECUCION,
        ER.NUMERO_DOCUMENTO_SOPORTE,
        A.NUMERO_ACUERDO,
        A.NOMBRE_ACUERDO,
        P.NOMBRE_PROVEEDOR,
        TR.NOMBRE,
        CR.NOMBRE,
        ER.MONTO_REBATE,
        ER.IDESTADO,
        E.NOMBRE,
        ER.FECHA_REGISTRO
    ORDER BY
        CASE 
            WHEN ER.IDESTADO = 1 THEN 1   -- PENDIENTE
            WHEN ER.IDESTADO = 6 THEN 2   -- PAGADO
        END,
        ER.FECHA_REGISTRO DESC;
END
GO

CREATE OR ALTER PROCEDURE SP_DETALLE_PAGO_EJECUCION_REBATE
    @ID_EJECUCION INT
AS
BEGIN
    SET NOCOUNT ON;

    SELECT
        DPR.ID_DETALLE_PAGO    AS IdDetallePago,
        PR.NUMERO_DOCUMENTO    AS DocumentoPago,
        DPR.MONTO_PAGADO       AS MontoPagado,
        TD.NOMBRE              AS TipoDocumento,
		DPR.USUARIO_PAGO       AS usuarioPago,
        DPR.FECHA_REGISTRO     AS FechaRegistro,
        DPR.COMPROBANTE        AS Comprobante
    FROM DETALLE_PAGO_REBATE DPR
    LEFT JOIN PAGO_REBATE PR 
        ON PR.ID_PAGO_REBATE = DPR.ID_PAGO_REBATE
    LEFT JOIN TIPO_DOCUMENTO_PAGO TD 
        ON TD.ID_TIPO_DOC = DPR.ID_TIPO_DOC
    WHERE DPR.ID_EJECUCION = @ID_EJECUCION
    ORDER BY DPR.FECHA_REGISTRO ASC;
END
