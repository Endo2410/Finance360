-- Obtener acuerdos
CREATE OR ALTER PROCEDURE SP_OBTENER_ACUERDO_REBATE
AS
BEGIN
    SET NOCOUNT ON;

    SELECT
        A.ID_ACUERDO,
        A.NUMERO_ACUERDO,
        A.NOMBRE_ACUERDO,
        A.VALOR_CRITERIO,
        A.GANANCIA,
        A.FECHA_INICIO,
        A.FECHA_FIN,
        A.FECHA_REGISTRO,
        A.USUARIO_CREACION,
        A.DOCUMENTO,
        A.COMENTARIO,

        P.ID_PROVEEDOR,
        P.NOMBRE_PROVEEDOR,

        MO.ID_MODALIDAD_OP,
        MO.NOMBRE AS MODALIDAD_OP,

        TR.ID_TIPO_REBATE,
        TR.NOMBRE AS TIPO_REBATE,

        CR.ID_CRITERIO,
        CR.NOMBRE AS CRITERIO,

        PA.ID_PAIS,
        PA.NOMBRE AS PAIS,

        M.ID_MONEDA,
        M.NOMBRE AS MONEDA,

        E.IDESTADO,
        E.NOMBRE AS ESTADO

    FROM ACUERDO_REBATE A
    INNER JOIN PROVEEDORES P ON P.ID_PROVEEDOR = A.ID_PROVEEDOR
    INNER JOIN MODALIDAD_OPERACION MO ON MO.ID_MODALIDAD_OP = A.ID_MODALIDAD_OP
    INNER JOIN TIPO_REBATE TR ON TR.ID_TIPO_REBATE = A.ID_TIPO_REBATE
    INNER JOIN CRITERIO_REBATE CR ON CR.ID_CRITERIO = A.ID_CRITERIO
    INNER JOIN PAIS PA ON PA.ID_PAIS = A.ID_PAIS
    INNER JOIN MONEDA M ON M.ID_MONEDA = A.ID_MONEDA
    INNER JOIN ESTADO E ON E.IDESTADO = A.IDESTADO
    ORDER BY A.ID_ACUERDO ASC;  -- puedes cambiar a FECHA_REGISTRO si prefieres
END
GO


