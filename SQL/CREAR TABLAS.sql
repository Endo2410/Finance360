CREATE TABLE ROL (
    IDROL INT IDENTITY(1,1) PRIMARY KEY,
    NOMBRE VARCHAR(50) NOT NULL UNIQUE,
    DESCRIPCION VARCHAR(200),
    FECHAREGISTRO DATETIME NOT NULL DEFAULT GETDATE(),
