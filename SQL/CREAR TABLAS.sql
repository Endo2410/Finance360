CREATE TABLE VENCIDOS
(
    IDVENCIDO INT IDENTITY(1,1) PRIMARY KEY,
    IDORDENVENCIDO INT NOT NULL,           -- ID real de FSCDBd
    HQID INT NOT NULL,                     -- FK hacia PROVEEDORES
    NUMERO_ORDEN NVARCHAR(50),
    STATUS_ORDEN NVARCHAR(50) ,   -- CERRADO
	CONCEPTO   NVARCHAR(150) ,
    FECHA_CREACION DATETIME NOT NULL,
	USUARIO NVARCHAR(50) NOT NULL,
    TOTAL DECIMAL(18,2) NOT NULL,
    IDESTADO INT NOT NULL DEFAULT 5,      -- 5 = PENDIENTE
    IDUSUARIOPAGO INT NULL,               -- FK hacia USUARIO
    FECHA_PAGO DATETIME NULL,
    CONSTRAINT UQ_ORDENVEN_UNICA UNIQUE(IDORDENVENCIDO),
    CONSTRAINT FK_ESTADO FOREIGN KEY(IDESTADO) REFERENCES ESTADO(IDESTADO),
    CONSTRAINT FK_USUARIO_VEN FOREIGN KEY(IDUSUARIOPAGO) REFERENCES USUARIO(IDUSUARIO),
    CONSTRAINT FK_PROVEEDORVEN_HQID FOREIGN KEY(HQID) REFERENCES PROVEEDORES(HQID)
);
GO


CREATE TABLE PAGO_VENCIDO
(
    ID_PAGO INT IDENTITY PRIMARY KEY,
    ID_VENCIDO INT NOT NULL,
    NUMERO_DOCUMENTO VARCHAR(50) NOT NULL UNIQUE,
    FECHA_DOCUMENTO DATE,
    MONTO_TOTAL DECIMAL(18,2),
    OBSERVACION VARCHAR(300),
    IDESTADO INT NOT NULL, 
    FECHA_REGISTRO DATETIME DEFAULT GETDATE(),
    FOREIGN KEY (ID_VENCIDO) REFERENCES VENCIDOS(IDVENCIDO),
    FOREIGN KEY (IDESTADO) REFERENCES ESTADO(IDESTADO)
)
GO

CREATE TABLE DETALLE_PAGO_VENCIDO
(
    ID_DETALLE_PAGO INT IDENTITY PRIMARY KEY,
    ID_PAGO INT NOT NULL,
    MONTO_PAGADO DECIMAL(18,2) NOT NULL,
    ID_TIPO_DOC INT NOT NULL,
    COMPROBANTE VARCHAR(MAX) NULL,
    FECHA_REGISTRO DATETIME DEFAULT GETDATE(),
    FOREIGN KEY (ID_PAGO) REFERENCES PAGO_VENCIDO(ID_PAGO),
    FOREIGN KEY (ID_TIPO_DOC) REFERENCES TIPO_DOCUMENTO_PAGO(ID_TIPO_DOC)
)
GO

