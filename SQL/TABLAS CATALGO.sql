CREATE TABLE NOTA_CREDITO (
    ID_NC INT IDENTITY(1,1) PRIMARY KEY,

    -- PROVEEDOR
    ID_PROVEEDOR INT NOT NULL,

    -- DATOS DEL DOCUMENTO
    NUMERO_NC VARCHAR(50) NOT NULL,
    FECHA_EMISION DATE NOT NULL,
    MONTO DECIMAL(18,2) NOT NULL,

    -- ESTADO (ACTIVA, APLICADA, ANULADA)
    IDESTADO INT NOT NULL,

    DOCUMENTO_ADJUNTO VARCHAR(300),

    -- ORIGEN DEL DINERO
    TIPO_ORIGEN VARCHAR(20) NOT NULL, 
    -- 'PUBLICIDAD' | 'REBATE' | 'VENCIDO'

    ID_ORIGEN INT NOT NULL,
    -- ID_CAMPANIA / ID_EJECUCION_REBATE / ID_ESTADO_CUENTA

    NUMERO_DOCUMENTO_ORIGEN VARCHAR(50), -- <--- NUEVA COLUMNA

    FECHA_REGISTRO DATETIME NOT NULL DEFAULT GETDATE(),

    CONSTRAINT FK_NC_PROVEEDOR
        FOREIGN KEY (ID_PROVEEDOR) REFERENCES PROVEEDORES(ID_PROVEEDOR),

    CONSTRAINT FK_NC_ESTADO
        FOREIGN KEY (IDESTADO) REFERENCES ESTADO(IDESTADO)
);
GO


