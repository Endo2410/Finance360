    FOREIGN KEY (ID_MODALIDAD_OP) REFERENCES MODALIDAD_OPERACION(ID_MODALIDAD_OP),
    FOREIGN KEY (ID_TIPO_REBATE) REFERENCES TIPO_REBATE(ID_TIPO_REBATE),
    FOREIGN KEY (ID_CRITERIO) REFERENCES CRITERIO_REBATE(ID_CRITERIO),
    FOREIGN KEY (ID_PAIS) REFERENCES PAIS(ID_PAIS),           -- FK a tabla PAIS
    FOREIGN KEY (ID_MONEDA) REFERENCES MONEDA(ID_MONEDA),     -- FK a tabla MONEDA
    FOREIGN KEY (IDESTADO) REFERENCES ESTADO(IDESTADO)
);
GO

