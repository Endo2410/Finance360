CREATE TABLE ACUERDO_REBATE (
    ID_ACUERDO INT IDENTITY PRIMARY KEY,
	NOMBRE_ACUERDO VARCHAR(200),
    NUMERO_ACUERDO VARCHAR(20) NOT NULL,   -- Número de acuerdo automático
    ID_PROVEEDOR INT NOT NULL,
    ID_MODALIDAD_OP INT NOT NULL,          -- COMPRA / VENTA
    ID_TIPO_REBATE INT NOT NULL,           -- Volumen / Crecimiento / Metas
    ID_CRITERIO INT NOT NULL,              -- Mayor que, %, Incremento
