----CAMPAÑA PUBLICITARIA 
CREATE OR ALTER PROCEDURE SP_OBTENER_CAMPANIA_PUBLICITARIA
AS
BEGIN
    SELECT 
        C.ID_CAMPANIA,
        C.NUMERO_CAMPANIA,  -- agregado
        C.NOMBRE_CAMPANIA,
        C.MONTO_INVERSION,
        C.FECHA_INICIO,
        C.FECHA_FIN,
        C.FECHA_REGISTRO,

        P.ID_PROVEEDOR,
        P.NOMBRE_PROVEEDOR,

        TP.ID_TIPO_PUBLICIDAD,
        TP.NOMBRE AS TIPO_PUBLICIDAD,

        M.ID_MODALIDAD,
        M.NOMBRE AS MODALIDAD,

        PA.ID_PAIS,
        PA.NOMBRE AS PAIS,

        MO.ID_MONEDA,
        MO.NOMBRE AS MONEDA,

        E.IDESTADO,
        E.NOMBRE AS ESTADO
    FROM CAMPANIA_PUBLICITARIA C
    INNER JOIN PROVEEDORES P ON P.ID_PROVEEDOR = C.ID_PROVEEDOR
    INNER JOIN TIPO_PUBLICIDAD TP ON TP.ID_TIPO_PUBLICIDAD = C.ID_TIPO_PUBLICIDAD
    INNER JOIN MODALIDAD M ON M.ID_MODALIDAD = C.ID_MODALIDAD
    INNER JOIN PAIS PA ON PA.ID_PAIS = C.ID_PAIS
    INNER JOIN MONEDA MO ON MO.ID_MONEDA = C.ID_MONEDA
    INNER JOIN ESTADO E ON E.IDESTADO = C.IDESTADO
    ORDER BY C.FECHA_INICIO ASC; -- Las próximas campañas primero
END
GO


