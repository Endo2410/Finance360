(
    ID_ESTADO_CUENTA INT,
    MONTO_PAGADO DECIMAL(18,2),
    ID_TIPO_DOCUMENTO INT,
    COMPROBANTE VARCHAR(max) -- solo ruta/nombre del archivo
);
GO


CREATE OR ALTER PROCEDURE SP_REGISTRAR_PAGO_PUBLICIDAD
(
    @ID_CAMPANIA INT,
    @FECHA_DOCUMENTO DATE,
    @MONTO_TOTAL DECIMAL(18,2),
    @OBSERVACION VARCHAR(300),
    @DETALLE T_DETALLE_PAGO_PUBLICIDAD READONLY,
    @ID_PAGO INT OUTPUT,
    @NUMERO_DOCUMENTO_OUT VARCHAR(20) OUTPUT
)
AS
BEGIN
    SET NOCOUNT ON;

    DECLARE 
        @CORRELATIVO INT,
        @LARGO INT;

    BEGIN TRY
        BEGIN TRAN;

        -- Obtener el siguiente número de documento
        SELECT @CORRELATIVO = ISNULL(MAX(CAST(NUMERO_DOCUMENTO AS INT)), 0) + 1
        FROM PAGO_PUBLICIDAD;

        -- Mínimo 4 dígitos
        SET @LARGO = CASE WHEN LEN(@CORRELATIVO) < 4 THEN 4 ELSE LEN(@CORRELATIVO) END;

        -- Formatear con ceros a la izquierda
        SET @NUMERO_DOCUMENTO_OUT = RIGHT(REPLICATE('0', @LARGO) + CAST(@CORRELATIVO AS VARCHAR), @LARGO);

        -- Insertar pago principal
        INSERT INTO PAGO_PUBLICIDAD
        (
            ID_CAMPANIA,
            NUMERO_DOCUMENTO,
            FECHA_DOCUMENTO,
            MONTO_TOTAL,
            OBSERVACION,
            IDESTADO,
            FECHA_REGISTRO
        )
        VALUES
        (
            @ID_CAMPANIA,
            @NUMERO_DOCUMENTO_OUT,
            @FECHA_DOCUMENTO,
            @MONTO_TOTAL,
            @OBSERVACION,
            6,
            GETDATE()
        );

        SET @ID_PAGO = SCOPE_IDENTITY();

        -- Insertar los pagos tal como vienen en @DETALLE
        INSERT INTO DETALLE_PAGO_PUBLICIDAD
        (
            ID_PAGO,
            ID_ESTADO_CUENTA,
            MONTO_PAGADO,
            ID_TIPO_DOC,
            COMPROBANTE
        )
        SELECT
            @ID_PAGO,
            ID_ESTADO_CUENTA,
            MONTO_PAGADO,
            ID_TIPO_DOCUMENTO,
            COMPROBANTE
        FROM @DETALLE;

        COMMIT;
    END TRY
    BEGIN CATCH
        ROLLBACK;
        THROW;
    END CATCH
END;


CREATE OR ALTER PROCEDURE SP_LISTA_CAMPANIAS_PUBLICIDAD
AS
BEGIN
    SET NOCOUNT ON;

    SELECT
        C.ID_CAMPANIA,
        C.NUMERO_CAMPANIA,
        C.NOMBRE_CAMPANIA,

        P.NOMBRE_PROVEEDOR,
        TP.NOMBRE AS TIPO_PUBLICIDAD,
        M.NOMBRE AS MODALIDAD,
        PA.NOMBRE AS PAIS,
        MO.NOMBRE AS MONEDA,

        C.MONTO_INVERSION,

        ISNULL(SUM(PP.MONTO_TOTAL), 0) AS MONTO_PAGADO,
        C.MONTO_INVERSION - ISNULL(SUM(PP.MONTO_TOTAL), 0) AS SALDO_PENDIENTE,

        EC.NOMBRE AS ESTADO_CAMPANIA,

        C.IDESTADO_PAGO AS ID_ESTADO_PAGO,   -- 🔥 CLAVE
        EP.NOMBRE AS ESTADO_PAGO,

        C.FECHA_INICIO,
        C.FECHA_FIN
    FROM CAMPANIA_PUBLICITARIA C
        INNER JOIN PROVEEDORES P ON P.ID_PROVEEDOR = C.ID_PROVEEDOR
        INNER JOIN TIPO_PUBLICIDAD TP ON TP.ID_TIPO_PUBLICIDAD = C.ID_TIPO_PUBLICIDAD
        INNER JOIN MODALIDAD M ON M.ID_MODALIDAD = C.ID_MODALIDAD
        INNER JOIN PAIS PA ON PA.ID_PAIS = C.ID_PAIS
        INNER JOIN MONEDA MO ON MO.ID_MONEDA = C.ID_MONEDA
        INNER JOIN ESTADO EC ON EC.IDESTADO = C.IDESTADO
        LEFT JOIN ESTADO EP ON EP.IDESTADO = C.IDESTADO_PAGO
        LEFT JOIN PAGO_PUBLICIDAD PP ON PP.ID_CAMPANIA = C.ID_CAMPANIA
    GROUP BY
        C.ID_CAMPANIA,
        C.NUMERO_CAMPANIA,
        C.NOMBRE_CAMPANIA,
        P.NOMBRE_PROVEEDOR,
        TP.NOMBRE,
        M.NOMBRE,
        PA.NOMBRE,
        MO.NOMBRE,
        C.MONTO_INVERSION,
        EC.NOMBRE,
        C.IDESTADO_PAGO,        -- 🔥 OBLIGATORIO
        EP.NOMBRE,
        C.FECHA_INICIO,
        C.FECHA_FIN
    ORDER BY C.FECHA_INICIO ASC;
END
GO


CREATE OR ALTER PROCEDURE SP_DETALLE_PAGO_CAMPANIA
    @ID_CAMPANIA INT
AS
BEGIN
    SELECT 
        DP.ID_DETALLE_PAGO AS IdDetallePago,
        PP.NUMERO_DOCUMENTO AS DocumentoPago,
        DP.MONTO_PAGADO AS MontoPagado,
        TD.NOMBRE AS TipoDocumento,
        PP.FECHA_DOCUMENTO AS FechaDocumento,
        DP.FECHA_REGISTRO AS FechaRegistro,
        DP.COMPROBANTE AS Comprobante
    FROM DETALLE_PAGO_PUBLICIDAD DP
    INNER JOIN PAGO_PUBLICIDAD PP ON PP.ID_PAGO = DP.ID_PAGO
    LEFT JOIN TIPO_DOCUMENTO_PAGO TD ON TD.ID_TIPO_DOC = DP.ID_TIPO_DOC
    WHERE PP.ID_CAMPANIA = @ID_CAMPANIA
    ORDER BY DP.FECHA_REGISTRO ASC;
END
