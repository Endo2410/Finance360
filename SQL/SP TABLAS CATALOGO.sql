--ESTADO 
CREATE OR ALTER PROCEDURE SP_OBTENER_ESTADO
AS
BEGIN
    SET NOCOUNT ON;

    SELECT 
        IDESTADO,
        NOMBRE,
        DESCRIPCION,
        MODULO,
        FECHAREGISTRO
    FROM ESTADO
    ORDER BY NOMBRE;
END
GO

CREATE OR ALTER PROCEDURE SP_CREAR_ESTADO
    @NOMBRE VARCHAR(50),
    @DESCRIPCION VARCHAR(200) = NULL,
    @MODULO VARCHAR(50) = NULL
AS
BEGIN
    SET NOCOUNT ON;

    -- Validar duplicado por nombre
    IF EXISTS (SELECT 1 FROM ESTADO WHERE NOMBRE = @NOMBRE)
    BEGIN
        RAISERROR('El estado ya existe.',16,1);
        RETURN;
    END

    INSERT INTO ESTADO (NOMBRE, DESCRIPCION, MODULO)
    VALUES (@NOMBRE, @DESCRIPCION, @MODULO);
END
GO

CREATE OR ALTER PROCEDURE SP_EDITAR_ESTADO
    @IDESTADO INT,
    @NOMBRE VARCHAR(50),
    @DESCRIPCION VARCHAR(200) = NULL,
    @MODULO VARCHAR(50) = NULL
AS
BEGIN
    SET NOCOUNT ON;

    -- Validar existencia
    IF NOT EXISTS (SELECT 1 FROM ESTADO WHERE IDESTADO = @IDESTADO)
    BEGIN
        RAISERROR('El estado no existe.',16,1);
        RETURN;
    END

    -- Validar duplicado en otro registro
    IF EXISTS (SELECT 1 FROM ESTADO WHERE NOMBRE = @NOMBRE AND IDESTADO <> @IDESTADO)
    BEGIN
        RAISERROR('Ya existe otro estado con el mismo nombre.',16,1);
        RETURN;
    END

    UPDATE ESTADO
    SET NOMBRE = @NOMBRE,
        DESCRIPCION = @DESCRIPCION,
        MODULO = @MODULO
    WHERE IDESTADO = @IDESTADO;
END
GO


