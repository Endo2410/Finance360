---ESTADO PUBLICIDAD CORRECTO 
CREATE OR ALTER PROCEDURE SP_OBTENER_ESTADO_CUENTA_PUBLICIDAD
    @ID_CAMPANIA INT = NULL  -- parámetro opcional, si es NULL trae todas las campañas
AS
BEGIN
    SET NOCOUNT ON;

    SELECT
        EC.ID_ESTADO_CUENTA,
        EC.ID_CAMPANIA,
        C.NUMERO_CAMPANIA,       -- Código de campaña
        C.NOMBRE_CAMPANIA,       -- Nombre de campaña
        P.NOMBRE_PROVEEDOR,
        EC.NUMERO_CUOTA,
        EC.FECHA_PAGO_PROGRAMADA,
        EC.MONTO_CUOTA,
        E.NOMBRE AS ESTADO,
        EC.FECHA_REGISTRO
    FROM ESTADO_CUENTA_PUBLICIDAD EC
    INNER JOIN CAMPANIA_PUBLICITARIA C 
        ON C.ID_CAMPANIA = EC.ID_CAMPANIA
    INNER JOIN PROVEEDORES P 
        ON P.ID_PROVEEDOR = C.ID_PROVEEDOR
    INNER JOIN ESTADO E 
        ON E.IDESTADO = EC.IDESTADO
    WHERE EC.IDESTADO = 5  -- Pendiente
      AND (@ID_CAMPANIA IS NULL OR EC.ID_CAMPANIA = @ID_CAMPANIA)
    ORDER BY EC.FECHA_PAGO_PROGRAMADA;
END
GO


